const ATTRIBUTE_FALLBACK = {
    fire: ["flame", "烈焰冲击"],
    water: ["water", "苍流斩"],
    wind: ["wind", "疾风连斩"],
    earth: ["earth", "大地震击"],
    light: ["light", "光耀突袭"],
    dark: ["dark", "暗影终结"],
    none: ["arcane", "灵能冲击"],
};

function moveFromName(name, fallback) {
    const parts = String(name).split(/[·・]/).map(part => part.trim()).filter(Boolean);
    return parts.length > 1 ? parts.at(-1) : fallback;
}

export function getMonsterCinematicProfile(card = {}) {
    if (String(card.rarity || "N").toUpperCase() === "N") return null;
    const name = String(card.name || "");
    const matched = CHARACTER_STYLES.find(([pattern]) => pattern.test(name));
    const fallback = ATTRIBUTE_FALLBACK[card.attribute || card.element || "none"] || ATTRIBUTE_FALLBACK.none;
    const [, style, defaultMove, attackStyle = style] = matched || [null, ...fallback];
    return {
        style,
        signatureMove: defaultMove,
        summonStyle: style,
        attackStyle,
        summonTitle: moveFromName(name, defaultMove),
        attackTitle: moveFromName(name, defaultMove),
        characterSpecific: !!matched,
    };
}
